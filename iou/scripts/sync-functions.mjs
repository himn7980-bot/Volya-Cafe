#!/usr/bin/env node
// Copies the shared pure-TS code and the notification texts into
// supabase/functions/_shared/generated so Edge Functions (Deno) can use them.
// Edge Functions only bundle files inside supabase/functions, and Deno needs
// explicit ".ts" import extensions, so this is a build step, not a symlink.
//
//   npm run functions:sync           write the files
//   npm run functions:sync -- --check   fail if they are out of date (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'supabase', 'functions', '_shared', 'generated');
const check = process.argv.includes('--check');

const SHARED = ['calendars', 'currencies', 'digits', 'money', 'format', 'notifications'];
const HEADER = '// GENERATED by scripts/sync-functions.mjs from src/shared. Do not edit; run `npm run functions:sync`.\n';

const files = new Map();
for (const name of SHARED) {
  const src = fs.readFileSync(path.join(root, 'src', 'shared', `${name}.ts`), 'utf8');
  files.set(`${name}.ts`, HEADER + src.replace(/from '\.\/([\w-]+)'/g, "from './$1.ts'"));
}

// Only what notifications need, per language.
const strings = {};
const localesDir = path.join(root, 'src', 'i18n', 'locales');
for (const file of fs.readdirSync(localesDir).filter((f) => f.endsWith('.json')).sort()) {
  const data = JSON.parse(fs.readFileSync(path.join(localesDir, file), 'utf8'));
  strings[file.replace(/\.json$/, '')] = {
    meta: {
      nativeDigits: data.meta.nativeDigits,
      defaultDigits: data.meta.defaultDigits,
      defaultCalendar: data.meta.defaultCalendar,
    },
    push: data.push,
    reminders: data.reminders,
    currency: { toman: data.currency.toman },
    months: data.months,
    date: data.date,
  };
}
files.set('strings.json', JSON.stringify(strings, null, 1) + '\n');

let stale = [];
fs.mkdirSync(outDir, { recursive: true });
for (const [name, content] of files) {
  const target = path.join(outDir, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === content) continue;
  if (check) stale.push(name);
  else fs.writeFileSync(target, content);
}
if (check && stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run: npm run functions:sync`);
  process.exit(1);
}
console.log(check ? 'Edge Function copies are up to date.' : `Wrote ${files.size} files to supabase/functions/_shared/generated.`);
